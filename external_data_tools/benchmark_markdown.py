"""Render evaluated benchmark artifacts as a human-readable Markdown report."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from external_data_tools.benchmark_evaluation import as_float, as_int, unique
from external_data_tools.benchmark_report_data import CASE_TITLES, as_list


def render_benchmark_markdown(
    summary_path: Path,
    summary: dict[str, Any],
    cases: list[dict[str, Any]],
    setup: dict[str, Any],
    evaluation: dict[str, Any],
) -> str:
    lines = [
        "# Semiconductor Low-Pressure Plasma Reaction-Network Benchmark",
        "",
        "## Title And Scope",
        "",
        "This report evaluates mechanism readiness, data coverage, missing-data transparency, "
        "and benchmark workflow for:",
    ]
    lines.extend(f"- {CASE_TITLES[case_id]} (`{case_id}`)" for case_id in CASE_TITLES)
    lines.extend(
        [
            "",
            "The generated YAML reports and metrics are the source of truth; this Markdown "
            "report is a point-in-time snapshot.",
            "",
        ]
    )
    for section in (
        _execution_summary(summary, setup, evaluation),
        _case_summary(cases, evaluation),
        _case_status_details(evaluation),
        _ar_o2_evaluation(cases),
        _practical_usefulness(cases, evaluation),
        _warnings_and_limitations(evaluation),
        _recommended_actions(evaluation),
        _appendix(summary_path, cases, setup),
    ):
        lines.extend(section)
    return "\n".join(lines) + "\n"


def _execution_summary(
    summary: dict[str, Any],
    setup: dict[str, Any],
    evaluation: dict[str, Any],
) -> list[str]:
    counts = evaluation["status_counts"]
    lines = [
        "## Execution Summary",
        "",
        f"- Report generated at: {evaluation['generated_at']}",
        f"- Benchmark summary timestamp: {summary.get('generated_at', 'unknown')}",
        "- Benchmark ids: "
        + ", ".join(str(item.get("id")) for item in as_list(summary.get("benchmarks"))),
        f"- Passed workflow cases: {counts['passed']}",
        f"- Warning cases: {counts['warning']}",
        f"- Failed checks: {counts['failed']}",
    ]
    if setup.get("report_path"):
        lines.append(f"- Setup report: `{setup['report_path']}`")
    return [*lines, ""]


def _case_summary(cases: list[dict[str, Any]], evaluation: dict[str, Any]) -> list[str]:
    by_id = {item["case_id"]: item for item in evaluation["case_evaluations"]}
    lines = [
        "## Case-By-Case Summary",
        "",
        "| Case | Status | Species | Reactions | Electron | Ion-neutral | Score | "
        "Xsec coverage | DNT property ready | Missing actions | Provenance |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for case in cases:
        metrics = case["metrics"]
        values = [
            case["title"],
            ", ".join(by_id.get(case["id"], {}).get("statuses", [])),
            str(as_int(metrics.get("n_species"))),
            str(as_int(metrics.get("n_reactions"))),
            str(as_int(metrics.get("n_electron_reactions"))),
            str(as_int(metrics.get("n_ion_neutral_reactions"))),
            f"{as_float(metrics.get('expectation_score')):.2f}",
            f"{as_float(metrics.get('cross_section_asset_coverage_fraction')):.2f}",
            str(as_int(metrics.get("n_dnt_property_ready_pairs"))),
            str(as_int(metrics.get("n_missing_plan_actions"))),
            f"{as_float(metrics.get('provenance_coverage_fraction')):.2f}",
        ]
        lines.append("| " + " | ".join(values) + " |")
    return [*lines, ""]


def _case_status_details(evaluation: dict[str, Any]) -> list[str]:
    lines = ["## Case Status Details", ""]
    for item in evaluation["case_evaluations"]:
        lines.extend([f"### {item['title']}", f"- Status tags: {', '.join(item['statuses'])}"])
        lines.extend(f"- failed: {message}" for message in item["failures"])
        lines.extend(f"- warning: {message}" for message in item["warnings"])
        if not item["failures"] and not item["warnings"]:
            lines.append(
                "- passed: no benchmark warnings or failures were generated by the report rules."
            )
        lines.append("")
    return lines


def _ar_o2_evaluation(cases: list[dict[str, Any]]) -> list[str]:
    case = next((item for item in cases if item["id"] == "ar_o2_simple"), None)
    lines = ["## Ar/O2 Specific Evaluation", ""]
    if case is None:
        return [
            *lines,
            "- FAILED: Ar/O2 simple oxygen plasma case was not present in the summary.",
            "",
        ]
    reactions = case["reactions"]
    states = _state_ids(case["states"])
    o2_types = _o2_electron_types(reactions)
    channel_ids = _reaction_ids(reactions)
    lines.extend(
        _check(f"O2 electron {reaction_type} reaction type", reaction_type in o2_types)
        for reaction_type in ("elastic", "ionization", "dissociation", "attachment")
    )
    lines.extend(
        [
            _check(
                "ion-neutral family exists",
                any(reaction.get("family") == "ion_neutral" for reaction in reactions),
            ),
            _check(
                "Ar+ + O2 channel exists when fixture is present",
                bool({"Arp_O2_elastic", "Arp_O2_charge_transfer"} & channel_ids),
                warning=True,
            ),
            _check("O species present or generated", "O" in states),
            _check("O- species present or generated", "O-" in states),
            "",
        ]
    )
    return lines


def _state_ids(states: list[Any]) -> set[str]:
    return {str(item.get("id")) for item in states if isinstance(item, dict)}


def _o2_electron_types(reactions: list[Any]) -> set[str]:
    return {
        str(reaction.get("type"))
        for reaction in reactions
        if isinstance(reaction, dict)
        and reaction.get("family") == "electron"
        and "O2" in str(reaction.get("equation", ""))
    }


def _reaction_ids(reactions: list[Any]) -> set[str]:
    return {str(reaction.get("id")) for reaction in reactions if isinstance(reaction, dict)}


def _practical_usefulness(cases: list[dict[str, Any]], evaluation: dict[str, Any]) -> list[str]:
    lines = ["## Practical Modeling Usefulness", ""]
    for case, case_evaluation in zip(cases, evaluation["case_evaluations"], strict=True):
        metrics = case["metrics"]
        expectations = case["report"].get("expectations", {})
        lines.extend(
            [
                f"### {case['title']}",
                _check(
                    "at least one electron reaction",
                    as_int(metrics.get("n_electron_reactions")) > 0,
                ),
                _check(
                    "at least one ion-neutral reaction",
                    as_int(metrics.get("n_ion_neutral_reactions")) > 0,
                ),
                _check("required species present", expectations.get("missing_species") == []),
                _check(
                    "required reaction families present",
                    expectations.get("missing_reaction_families") == [],
                ),
                _check(
                    "charge/element balance errors are zero",
                    as_int(metrics.get("validation_error_count")) == 0,
                ),
                _check(
                    "missing data items are actionable",
                    as_int(metrics.get("n_missing_data_items")) == 0
                    or as_int(metrics.get("n_missing_plan_actions")) > 0,
                    warning=True,
                ),
                _check(
                    "DNT pairs identified", as_int(metrics.get("n_dnt_tasks")) > 0, warning=True
                ),
                _check(
                    "at least one electron reaction has a cross-section asset",
                    as_int(metrics.get("n_reactions_with_cross_section_asset")) > 0,
                    warning=True,
                ),
                _check(
                    "inferred fraction is not too high",
                    as_float(metrics.get("inferred_reaction_fraction")) <= 0.5,
                    warning=True,
                ),
            ]
        )
        if case_evaluation["recommendations"]:
            lines.append(f"- needs domain review: {'; '.join(case_evaluation['recommendations'])}")
        lines.append("")
    return lines


def _warnings_and_limitations(evaluation: dict[str, Any]) -> list[str]:
    lines = ["## Warnings And Limitations", ""]
    lines.extend(f"- warning: {message}" for message in evaluation["limitations"])
    if evaluation["setup_failed"]:
        lines.append("- failed: required fixture data was missing during setup.")
    return [*lines, ""]


def _recommended_actions(evaluation: dict[str, Any]) -> list[str]:
    recommendations = [
        recommendation
        for item in evaluation["case_evaluations"]
        for recommendation in item["recommendations"]
    ]
    actions = unique(recommendations)
    if not actions:
        actions = ["No data-gap actions were generated by the current evaluation rules."]
    return [
        "## Recommended Next Actions",
        "",
        *(f"- {item}" for item in actions),
        "",
    ]


def _appendix(
    summary_path: Path,
    cases: list[dict[str, Any]],
    setup: dict[str, Any],
) -> list[str]:
    lines = ["## Appendix", "", f"- Summary: `{summary_path}`"]
    if setup.get("report_path"):
        lines.append(f"- Setup report: `{setup['report_path']}`")
    for case in cases:
        lines.extend(
            [
                f"- {case['title']} report: `{case['report_path']}`",
                f"- {case['title']} metrics: `{case['metrics_path']}`",
                f"- {case['title']} missing plan: `{case['missing_plan_path']}`",
                f"- {case['title']} source profile: `{case['report'].get('source_profile')}`",
            ]
        )
        plots = _plot_paths(_output_path(case))
        lines.extend(
            (f"- {case['title']} plot: `{path}`" for path in plots)
            if plots
            else [f"- {case['title']} plots: none detected"]
        )
    return [*lines, ""]


def _output_path(case: dict[str, Any]) -> Path | None:
    value = case["report"].get("output")
    return Path(str(value)) if value else None


def _plot_paths(output_path: Path | None) -> list[Path]:
    if output_path is None or not output_path.exists():
        return []
    return sorted(
        [
            *output_path.rglob("*.svg"),
            *output_path.rglob("*.png"),
            *output_path.rglob("*.pdf"),
        ]
    )


def _check(label: str, passed: bool, *, warning: bool = False) -> str:
    status = "passed" if passed else ("warning" if warning else "failed")
    return f"- {status}: {label}"
